const BY_AGE = new Map(ERA_NODES.map(item => [item.age, item]))

export function eraAges(): number[] {
  return [...BY_AGE.keys()]
}

export function nearestEraAge(age: number): number {
  let nearest = ERA_NODES[0].age
  for (const nodeAge of BY_AGE.keys()) {
    if (Math.abs(nodeAge - age) < Math.abs(nearest - age)) nearest = nodeAge
  }
  return nearest
}

export function eraNodeForAge(age: number): EraNode {
  return BY_AGE.get(age) ?? BY_AGE.get(nearestEraAge(age))!
}

export function eraChoice(age: number, choiceId: string): EraChoice | undefined {
  return eraNodeForAge(age).choices.find(item => item.id === choiceId)
}

export const OWN_CHOICE_ID = 'own'

export function isOwnChoice(choice: Pick<EraChoice, 'id'>): boolean {
  return choice.id === OWN_CHOICE_ID
}

export function ownChoice(age: number, label = ''): EraChoice {
  const written = label.trim().slice(0, 40)
  return {
    id: OWN_CHOICE_ID,
    label: written || '写下你自己的路',
    peer: 0,
    reason: written
      ? `这是你亲口写下的「${written}」。不是同龄人占比。后面几年会带着这句走。`
      : '左边这些只是常见的分岔。你的路可以不在里面。先写下，再种到星球上。',
    flowerKind: 7,
    npc: {
      name: '你自己',
      identity: written ? `${age}岁亲口写下的路` : '还没写下的那一条',
      proposition: written || '这一年的路，由你命名。',
      match: written ? `这是你写下的原话：${written}。` : '先写下，后面才会按你的路去找人。',
      causal: {
        background: `${age}岁这一年，公开选项没有穷尽所有活法。`,
        options: written ? `${written} / 常见的路 / 新出现的路` : '写下自己的路 / 选一朵现成的花',
        choice: written || '尚未写下',
        cost: '自己命名的路没有现成的同龄人百分比。',
        reflection: written ? '后面的选择会记得这句。' : '写下来，路径才是你的。',
      },
    },
  }
}

export function withOwnChoice(node: EraNode, label = ''): EraNode {
  return {
    ...node,
    choices: [...node.choices.filter(item => item.id !== OWN_CHOICE_ID), ownChoice(node.age, label)],
  }
}

export const SIGNAL_SLOTS = ['A · 同代相近', 'A · 同代同行', 'A · 同代旁路', 'B · 跨代对照'] as const
export type PortraitMode = 'planted' | 'backtrack'

export type SignalPortrait = {
  slot: string
  kind: 'A' | 'B'
  npc: EraNpc
  note: string
  choice: EraChoice
  age: number
}

export function signalPortraits(age: number, choiceId: string, mode: PortraitMode = 'planted'): SignalPortrait[] {
  const current = eraNodeForAge(age)
  const chosen = eraChoice(age, choiceId) ?? current.choices[0]
  const others = current.choices.filter(item => item.id !== chosen.id && item.id !== OWN_CHOICE_ID)
  const crossNode = eraNodeForAge(age < 40 ? age + 25 : Math.max(5, age - 25))
  const cross = crossNode.choices.find(item => item.id === chosen.id)
    ?? crossNode.choices[chosen.flowerKind % crossNode.choices.length]
    ?? current.choices[0]
  if (mode === 'backtrack') {
    return others.slice(0, 3).map((item, index) => ({
      slot: index === 0 ? SIGNAL_SLOTS[2] : `${SIGNAL_SLOTS[2]} · ${item.id}`,
      kind: 'A' as const,
      npc: { ...item.npc, match: `同一年，TA 走了另一条路：${item.label}。` },
      note: item.label,
      choice: item,
      age: current.age,
    }))
  }
  return [
    { slot: SIGNAL_SLOTS[0], kind: 'A', npc: chosen.npc, note: '也有人走了相近的路，这是对照，不是匹配分数', choice: chosen, age: current.age },
    { slot: SIGNAL_SLOTS[3], kind: 'B', npc: { ...cross.npc, match: `在另一个年纪，TA 也面对过相近的分岔。` }, note: '相似的困境，不同的时代', choice: chosen, age: crossNode.age },
  ]
}

