const BY_AGE = new Map(ERA_NODES.map(item => [item.age, item]))

export function nearestEraAge(age: number): number {
  let nearest = ERA_NODES[0].age
  for (const nodeAge of BY_AGE.keys()) {
    if (Math.abs(nodeAge - age) < Math.abs(nearest - age)) nearest = nodeAge
  }
  return nearest
}

export function eraNodeForAge(age: number): EraNode {
  return BY_AGE.get(age) ?? BY_AGE.get(nearestEraAge(age))!
}

export function eraChoice(age: number, choiceId: string): EraChoice | undefined {
  return eraNodeForAge(age).choices.find(item => item.id === choiceId)
}

export const SIGNAL_SLOTS = ['同代 · 相近选择', '同代 · 不同取舍', '跨代 · 相似困境'] as const

export type SignalPortrait = {
  slot: (typeof SIGNAL_SLOTS)[number]
  npc: EraNpc
  note: string
  choice: EraChoice
  age: number
}

export function signalPortraits(age: number, choiceId: string): SignalPortrait[] {
  const current = eraNodeForAge(age)
  const chosen = eraChoice(age, choiceId) ?? current.choices[0]
  const other = current.choices.find(item => item.id !== chosen.id) ?? current.choices[0]
  const crossNode = eraNodeForAge(age < 40 ? age + 25 : Math.max(5, age - 25))
  const cross = crossNode.choices[chosen.flowerKind % crossNode.choices.length] ?? current.choices[0]
  return [
    { slot: SIGNAL_SLOTS[0], npc: chosen.npc, note: `${chosen.peer}% 的同龄人这样选`, choice: chosen, age: current.age },
    { slot: SIGNAL_SLOTS[1], npc: { ...other.npc, match: `同一年，TA 走了另一条路：${other.label}。` }, note: other.label, choice: other, age: current.age },
    { slot: SIGNAL_SLOTS[2], npc: { ...cross.npc, match: `在另一个年纪，TA 也面对过相近的分岔。` }, note: '相似的困境，不同的时代', choice: cross, age: crossNode.age },
  ]
}

