function choice(
  id: string,
  label: string,
  peer: number,
  reason: string,
  name: string,
  identity: string,
  proposition: string,
  match: string,
  index: number,
  optionLine: string,
): EraChoice {
  const authored = CAUSAL[id]
  return {
    id, label, peer, reason,
    flowerKind: flowerKindAt(index),
    npc: {
      name, identity, proposition, match,
      causal: authored
        ? asCausal(authored)
        : {
            background: reason.split('。')[0] || reason,
            options: optionLine,
            choice: label,
            cost: reason.split('。')[1] || '这一年要付出去的，往往当时看不清。',
            reflection: proposition,
          },
    },
  }
}

function node(age: number, title: string, event: string, era: string, rows: Array<[string, string, number, string, string, string, string, string]>): EraNode {
  const optionLine = rows.map(row => row[1]).join(' / ')
  return {
    age, title, event, era,
    choices: rows.map((row, index) => choice(...row, index, optionLine)),
  }
}

