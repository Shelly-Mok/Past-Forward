function asCausal(parts: [string, string, string, string, string]): CausalChain {
  return { background: parts[0], options: parts[1], choice: parts[2], cost: parts[3], reflection: parts[4] }
}

export function flowerKindAt(index: number): FlowerKind {
  return (index % FLOWER_KIND_NAMES.length) as FlowerKind
}

export function paintFlowerKind(canvas: HTMLCanvasElement, kind: number) {
  const ctx = canvas.getContext('2d')
  if (!ctx) return
  canvas.width = 128
  canvas.height = 128
  ctx.imageSmoothingEnabled = false
  ctx.clearRect(0, 0, 128, 128)
  const cell = 4
  const dot = (tone: number, x: number, y: number, w = 1, h = 1) => {
    ctx.fillStyle = `rgb(${tone},${tone},${tone - 8})`
    ctx.fillRect(x * cell, y * cell, w * cell, h * cell)
  }
  dot(96, 11, 29, 10, 2)
  dot(140, 15, 18, 2, 11)
  const species = flowerKindAt(kind)
  if (species === 0) {
    for (const [x, y] of [[12, 10], [18, 10], [10, 14], [20, 14], [13, 18], [17, 18]]) dot(232, x, y, 3, 3)
    dot(250, 15, 13, 2, 2)
  } else if (species === 1) {
    for (const [x, y, w, h] of [[15, 8, 2, 4], [10, 11, 4, 2], [18, 11, 4, 2], [11, 16, 2, 3], [19, 16, 2, 3], [15, 17, 2, 3]]) dot(220, x, y, w, h)
    dot(188, 14, 12, 4, 4)
  } else if (species === 2) {
    dot(210, 13, 10, 6, 2)
    dot(236, 12, 12, 8, 6)
    dot(168, 14, 18, 4, 2)
  } else if (species === 3) {
    dot(240, 15, 8, 2, 10)
    dot(240, 11, 12, 10, 2)
    dot(240, 12, 9, 2, 2)
    dot(240, 18, 9, 2, 2)
    dot(240, 12, 15, 2, 2)
    dot(240, 18, 15, 2, 2)
    dot(255, 15, 12, 2, 2)
  } else {
    dot(200, 12, 14, 3, 2)
    dot(200, 17, 16, 3, 2)
    dot(230, 14, 8, 4, 6)
    dot(255, 15, 7, 2, 2)
  }
}

