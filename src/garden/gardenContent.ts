export function safeAvatarUrl(url?: string): string {
  const raw = String(url || '').trim()
  if (!raw) return ''
  try {
    const parsed = new URL(raw)
    if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') return ''
    const host = parsed.hostname.toLowerCase()
    if (host === 'zhimg.com' || host.endsWith('.zhimg.com') || host === 'zhihu.com' || host.endsWith('.zhihu.com')) return raw
    return ''
  } catch {
    return ''
  }
}

/** Live Zhihu photo when the search item has one; otherwise the hashed pixel face. */
export function npcFace(seed: string, avatar?: string): HTMLElement {
  const src = safeAvatarUrl(avatar)
  if (src) {
    const img = document.createElement('img')
    img.className = 'garden-npc-face'
    img.alt = ''
    img.width = 96
    img.height = 96
    img.referrerPolicy = 'no-referrer'
    img.src = src
    img.addEventListener('error', () => {
      const canvas = document.createElement('canvas')
      paintNpcPortrait(canvas, seed)
      img.replaceWith(canvas)
    }, { once: true })
    return img
  }
  const canvas = document.createElement('canvas')
  paintNpcPortrait(canvas, seed)
  return canvas
}

export function paintNpcPortrait(canvas: HTMLCanvasElement, seed: string) {
  const ctx = canvas.getContext('2d')
  if (!ctx) return
  const grid = 12
  canvas.width = 96
  canvas.height = 96
  ctx.imageSmoothingEnabled = false
  ctx.fillStyle = '#10100e'
  ctx.fillRect(0, 0, 96, 96)
  let hash = 2166136261
  for (let i = 0; i < seed.length; i++) hash = Math.imul(hash ^ seed.charCodeAt(i), 16777619)
  const cell = 96 / grid
  for (let y = 0; y < grid; y++) {
    for (let x = 0; x < grid / 2; x++) {
      hash = Math.imul(hash ^ (y * 31 + x), 16777619)
      if (y > 1 && y < 11 && (hash & 3) !== 0) {
        const tone = 150 + (hash & 47)
        ctx.fillStyle = `rgb(${tone},${tone},${tone - 10})`
        ctx.fillRect(x * cell, y * cell, cell, cell)
        ctx.fillRect((grid - 1 - x) * cell, y * cell, cell, cell)
      }
    }
  }
}
